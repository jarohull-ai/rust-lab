const dictionaries = { en, pl };

function interpolate(template: string, params: Params = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Params) => string;
  formatTime: (date?: Date) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export const I18nProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = window.localStorage.getItem('rust-lab.locale');
    return stored === 'pl' ? 'pl' : 'en';
  });

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nValue>(() => {
    const setLocale = (nextLocale: Locale) => {
      window.localStorage.setItem('rust-lab.locale', nextLocale);
      document.documentElement.lang = nextLocale;
      setLocaleState(nextLocale);
    };
    const t = (key: string, params: Params = {}) => {
      const template = dictionaries[locale][key] ?? en[key] ?? key;
      return interpolate(template, params);
    };
    const formatTime = (date = new Date()) =>
      date.toLocaleTimeString(locale === 'pl' ? 'pl-PL' : 'en-GB');
    return { locale, setLocale, t, formatTime };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
